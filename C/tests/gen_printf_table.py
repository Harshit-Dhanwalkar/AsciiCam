#!/usr/bin/env python3
"""Generate tests/printf_table.inc: (format, argument, expected) rows whose
expected text comes from Python's %-formatting, which matches C for subset
nl_printf supports.  Re-run: python3 tests/gen_printf_table.py"""

import itertools
import math
import os
import struct


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

rows = []
def c_differs(fmt, v):
    # Python zero-pads even with a precision and prints "0" for %.0d of 0;
    # C ignores 0 flag when a precision is given and prints nothing
    flags = fmt[1:].lstrip("-+ #")
    return ("." in fmt and flags[:1] == "0") or (".0" in fmt and v == 0 and "." in fmt and not any(c.isdigit() for c in fmt.split(".")[1][1:2]))

def add_int(fmt, v):
    if c_differs(fmt, v):
        return
    lit = "(-9223372036854775807LL-1)" if v == -9223372036854775808 else f"{v}LL"
    lit = f"(long long){lit}" if "l" in fmt else f"(int){lit}"
    rows.append(("I", fmt, lit, fmt.replace("ll", "").replace("l", "") % v))
def add_uint(fmt, v):
    if c_differs(fmt, v):
        return
    lit = f"(unsigned long long){v}ULL" if "l" in fmt else f"(unsigned){v}ULL"
    rows.append(("U", fmt, lit, fmt.replace("ll", "").replace("l", "") % v))
def add_dbl(fmt, v):
    lit = "__builtin_nan(\"\")" if math.isnan(v) else float(v).hex() if math.isfinite(v) else ("__builtin_inf()" if v > 0 else "(-__builtin_inf())")
    rows.append(("D", fmt, lit, fmt % v))
def add_str(fmt, s):
    rows.append(("S", fmt, cstr(s), fmt % s))

flags = ["", "-", "+", " ", "0", "-+", "+0", " 0", "-0"]
widths = ["", "1", "5", "12"]
precs = ["", ".0", ".1", ".3", ".8"]
ints = [0, 1, -1, 7, -7, 42, -42, 255, 99999, -99999, 2147483647, -2147483648]
for f, w, p in itertools.product(flags, widths, precs):
    for v in ints:
        add_int(f"%{f}{w}{p}d", v)
for f, w, p in itertools.product(["", "-", "0"], widths, [".1", ""]):
    for v in [0, 1, 255, 4096, 4294967295]:
        add_uint(f"%{f}{w}{p}u", v)
        add_uint(f"%{f}{w}{p}x", v)
        add_uint(f"%{f}{w}{p}X", v)
        add_uint(f"%{f}{w}{p}o", v)
for f, w in itertools.product(["", "#", "-#", "#0"], widths):
    for v in [1, 255, 48879]:
        add_uint(f"%{f}{w}x", v)
        add_uint(f"%{f}{w}X", v)
for v in [0, 9223372036854775807, -9223372036854775807 - 1]:
    add_int("%lld", v); add_int("%20ld", v); add_int("%-22lld|", v)
add_uint("%llu", 18446744073709551615)
add_uint("%lx", 18446744073709551615)

vals = [0.0, -0.0, 0.5, 1.5, 2.5, 3.5, 0.125, 0.375, 0.1, 0.2, 0.3, 1.0, -1.0,
        59.94, 29.97, 99.995, 9.9999995, 0.9999995, 123456789.123456789,
        1e15, 1e16, 1e22, 1e23, 1e300, 1.7976931348623157e308, 2.2250738585072014e-308,
        5e-324, 1e-10, 1.0/3, 2.0/3, 0.045, 0.055, 1.005, 2.675, 100.0, 1e-5,
        float("inf"), -float("inf"), float("nan")]
for v in vals:
    for fmt in ["%f", "%.0f", "%.1f", "%.2f", "%.3f", "%.10f", "%12.3f", "%-12.3f|",
                "%012.3f", "%+f", "% f", "%+.0f", "%.20f", "%#.0f", "%8.0f"]:
        if not math.isfinite(v) and "0" in fmt.split(".")[0][1:2]:
            continue  # zero flag with nan/inf: pad rule differs between libcs
        add_dbl(fmt, v)
# deterministic spread of random-ish doubles
import random

r = random.Random(1729)
for _ in range(300):
    bits = r.getrandbits(64)
    v = struct.unpack("<d", struct.pack("<Q", bits))[0]
    if not math.isfinite(v) or abs(v) > 1e60 or (v != 0 and abs(v) < 1e-60):
        v = r.uniform(-1000, 1000)
    add_dbl(r.choice(["%f", "%.2f", "%.9f", "%.17f", "%10.4f"]), v)
for _ in range(200):
    add_dbl(r.choice(["%.1f", "%.2f", "%.3f"]), round(r.uniform(0, 100), r.randint(1, 5)))

for f, w, p in itertools.product(["", "-"], ["", "3", "8"], ["", ".0", ".2", ".5"]):
    for s in ["", "a", "hello", "wide string here"]:
        add_str(f"%{f}{w}{p}s", s)

with open(os.path.join(os.path.dirname(__file__), "printf_table.inc"), "w") as out:
    out.write("/* generated by tests/gen_printf_table.py - do not edit */\n")
    for kind, fmt, lit, want in rows:
        out.write("ROW_%s(%s, %s, %s)\n" % (kind, cstr(fmt), lit, cstr(want)))
print(len(rows), "rows")

