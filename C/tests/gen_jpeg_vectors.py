#!/usr/bin/env python3
"""Writes tests/jpeg_vectors.inc: JPEG files for test_jpeg.c with the RGB that
libjpeg (through Pillow) decodes them to. Run:
    python3 tests/gen_jpeg_vectors.py > tests/jpeg_vectors.inc"""

import io
import math
import random

from PIL import Image


def scene(w, h):
    im = Image.new("RGB", (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            r = x * 255 // max(1, w - 1)
            g = y * 255 // max(1, h - 1)
            d = math.hypot(x - w * 0.6, y - h * 0.4) / max(w, h)
            b = int(200 * max(0.0, 1.0 - 3.0 * d)) + 30
            px[x, y] = (r, g, min(255, b))
    return im


def noise(w, h, seed):
    rnd = random.Random(seed)
    im = Image.new("RGB", (w, h))
    im.putdata([(rnd.randrange(256), rnd.randrange(256), rnd.randrange(256)) for _ in range(w * h)])
    return im


def jpeg(im, **kw):
    b = io.BytesIO()
    im.save(b, "JPEG", **kw)
    return b.getvalue()


def carray(name, data):
    return "static const uint8_t %s[] = {%s};\n" % (name, ",".join(str(v) for v in data))


# (name, bytes, w, h, max error, mean error limit x100) ; None expected = refused
vec = []


def add(name, im, maxerr, meanerr, **kw):
    data = jpeg(im, **kw)
    back = Image.open(io.BytesIO(data)).convert("RGB")
    vec.append((name, data, im.width, im.height, bytes(v for px in back.getdata() for v in px), maxerr, meanerr))

s = scene(21, 13)
add("s444", s, 4, 100, quality=90, subsampling=0)
add("s422", s, 40, 400, quality=90, subsampling=1)
add("s420", s, 40, 400, quality=90, subsampling=2)
add("gray", s.convert("L"), 3, 100, quality=85)
add("q30", scene(37, 29), 60, 600, quality=30, subsampling=2)
add("restart", scene(33, 25), 40, 400, quality=80, subsampling=2, restart_marker_blocks=3)
add("opt", noise(40, 40, 3), 4, 150, quality=95, subsampling=0, optimize=True)
add("noise_q50", noise(24, 24, 5), 4, 150, quality=50, subsampling=0)
add("big", scene(96, 64), 40, 400, quality=75, subsampling=2)
add("onepx", Image.new("RGB", (1, 1), (200, 100, 50)), 8, 600, quality=90)
add("wide", scene(200, 5), 40, 400, quality=80, subsampling=2)

bad = []
bad.append(("progressive", jpeg(scene(24, 16), quality=80, progressive=True)))
bad.append(("cmyk", jpeg(scene(24, 16).convert("CMYK"), quality=80)))

print("/* Generated by tests/gen_jpeg_vectors.py, do not edit */")
for name, data, w, h, exp, mx, mean in vec:
    print(carray("jpg_" + name, data), end="")
    print(carray("jrgb_" + name, exp), end="")
for name, data in bad:
    print(carray("jbad_" + name, data), end="")
print("static const jvec_t jvectors[] = {")
for name, data, w, h, exp, mx, mean in vec:
    print('    {"%s", jpg_%s, sizeof(jpg_%s), %d, %d, jrgb_%s, %d, %d},' % (name, name, name, w, h, name, mx, mean))
print("};")
print("static const jbad_t jbads[] = {")
for name, data in bad:
    print('    {"%s", jbad_%s, sizeof(jbad_%s)},' % (name, name, name))
print("};")
